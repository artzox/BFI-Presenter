#!/usr/bin/env python3
"""Builds tested_games.inc (name, status, note) from docs/tested-games.md for the manager app."""
import re, sys, pathlib

here = pathlib.Path(__file__).resolve().parent
md = (here.parent / "docs" / "tested-games.md").read_text(encoding="utf-8")

def clean(s):
    s = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", s)      # links
    s = s.replace("`", "").replace("\\~", "~").replace("**", "")
    return s.strip()

def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

rows = []
section = None
for line in md.splitlines():
    if line.startswith("| Game | Status"):
        section = "main"; continue
    if line.startswith("| Game | Notes"):
        section = "more"; continue
    if not line.startswith("|"):
        section = None if line.strip() else section
        continue
    if section is None or line.startswith("| ---"):
        continue
    cells = [clean(c) for c in line.strip().strip("|").split("|")]
    if section == "main" and len(cells) >= 5:
        rows.append((cells[0], cells[1], cells[4]))
    elif section == "more" and len(cells) >= 2:
        rows.append((cells[0], "Working", "" if cells[1] == "Standard setup" else cells[1]))

out = "// Generated by gen_tested.py from docs/tested-games.md -- do not edit.\n"
out += "".join("{ %s, %s, %s },\n" % (cstr(n), cstr(s), cstr(r)) for n, s, r in rows)
(here / "tested_games.inc").write_text(out, encoding="utf-8")
print(f"tested_games.inc: {len(rows)} games")

# The BFI shader, built into the app: used when the selected release doesn't carry it (or carries an older one).
fx = (here.parent / "shader" / "BFIPresenter_Shader.fx").read_text(encoding="utf-8")
assert ")BFIFX\"" not in fx
(here / "shader_fx.inc").write_text("// Generated by gen_tested.py from shader/BFIPresenter_Shader.fx -- do not edit.\n"
                                    "static const char kBundledShader[] = R\"BFIFX(" + fx + ")BFIFX\";\n", encoding="utf-8")
print(f"shader_fx.inc: {len(fx)} bytes")
